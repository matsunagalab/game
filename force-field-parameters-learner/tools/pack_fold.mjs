// Packs the text census from enumerate_fold.c into typed arrays stored as base64, so the single HTML file stays small.
//   node tools/pack_fold.mjs raw-fold-table.js > src/physics/fold-table.js
const { FOLD_ROWS: R, FOLD_QN, FOLD_QA, FOLD_TOTAL, CHARGES, NATIVE_F, MISFOLD } = await import(process.argv[2]);
const n = R.length / 8;
const key = new Uint32Array(n), logG = new Float32Array(n), rg = new Float32Array(n);
for (let i = 0; i < n; i++) {
  const [c, qn, qa, d, e, w, g, s] = R.slice(8 * i, 8 * i + 8);
  key[i] = c | qn << 4 | qa << 8 | (d + 16) << 12 | e << 17 | w << 20;
  logG[i] = Math.log(g); rg[i] = s / g;
}
const b64 = a => Buffer.from(a.buffer).toString('base64');
console.log(`// Generated by tools/enumerate_fold.c and tools/pack_fold.mjs. An exact census of all ${FOLD_TOTAL} 16-bead self-avoiding walks,
// tallied by the integers the energy depends on. Key bits: c 0-3, Qn 4-7, Qa 8-11, d+16 12-16, e 17-19, w 20-22.
export const FOLD_QN = ${FOLD_QN}, FOLD_QA = ${FOLD_QA}, FOLD_TOTAL = ${FOLD_TOTAL}, ROWS = ${n};
export const CHARGES = ${JSON.stringify(CHARGES)};
export const NATIVE_F = ${JSON.stringify(NATIVE_F)};
export const MISFOLD = ${JSON.stringify(MISFOLD)};
export const KEY_B64 = "${b64(key)}";
export const LOGG_B64 = "${b64(logG)}";
export const RG_B64 = "${b64(rg)}";`);
