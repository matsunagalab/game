// The crowding force at many distances, from long runs with both big disks held still. Writes src/sim/disktable.js.
// The stored force comes from thin skins (0.02 and 0.04), which keep the sharp packing peaks. The live print uses a
// wider skin, 0.07, because it must read in seconds; that column is kept too.
//   node tools/precompute_disks.mjs
import { Worker, isMainThread, parentPort } from 'node:worker_threads';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Disks } from '../src/sim/disks.js';

const here = dirname(fileURLToPath(import.meta.url));
const L = 24, big = 3, small = 0.7, n = 175;
const R3 = (x) => Math.round(x * 1000) / 1000;

function run({ d, seed }) {
  const box = new Disks({ L, big, small, nSmall: 0, seed: seed * 7 });
  box.frozen = true;
  box.bx = [L / 2 - d / 2, L / 2 + d / 2];
  box.by = [L / 2, L / 2];
  box.setCrowd(n);
  box.sweep(3000);
  const sum = [0, 0, 0];
  let c = 0;
  for (let s = 0; s < 150000; s++) {
    box.sweep(1);
    if (s % 2) continue;
    sum[0] += box.skinForce(0.02);
    sum[1] += box.skinForce(0.04);
    sum[2] += box.skinForce(0.07);
    c++;
  }
  return { d, seed, f02: sum[0] / c, f04: sum[1] / c, f07: sum[2] / c };
}

if (!isMainThread) {
  parentPort.on('message', (job) => parentPort.postMessage(run(job)));
} else {
  const grid = [];
  for (let k = 0; k <= 40; k++) grid.push(+(6.04 + k * 0.1).toFixed(2));
  const jobs = grid.flatMap((d) => [1, 2, 3].map((seed) => ({ d, seed })));
  const res = [];
  let at = 0;
  await new Promise((done) => {
    let live = 0;
    for (let i = 0; i < 3; i++) {
      const wk = new Worker(fileURLToPath(import.meta.url));
      const feed = () => { if (at < jobs.length) { wk.postMessage(jobs[at++]); live++; } else { wk.terminate(); if (!live) done(); } };
      wk.on('message', (m) => { res.push(m); live--; if (res.length % 30 === 0) console.log(res.length, '/', jobs.length); feed(); });
      feed();
    }
  });
  const rows = grid.map((d) => {
    const per = res.filter((r) => r.d === d);
    const m = (k) => per.reduce((s, v) => s + v[k], 0) / per.length;
    const each = per.map((v) => (v.f02 + v.f04) / 2);
    const F = each.reduce((a, b) => a + b, 0) / each.length;
    const err = Math.sqrt(each.reduce((s, v) => s + (v - F) ** 2, 0) / (each.length - 1) / each.length);
    return { d, F: R3(F), err: R3(err), live: R3(m('f07')) };
  });
  // Work from the far end inward, by trapezoids.
  let W = 0;
  const out = [...rows].reverse().map((r, i, a) => {
    if (i) W += ((a[i - 1].F + r.F) / 2) * (a[i - 1].d - r.d);
    return { ...r, W: R3(W) };
  }).reverse();
  out.forEach((r) => console.log(JSON.stringify(r)));
  writeFileSync(join(here, '../src/sim/disktable.js'), `// Generated by tools/precompute_disks.mjs. Force in kT per unit length, positive pushes the big disks apart.\n// F uses skins 0.02 and 0.04; live is the same long run read with the print's skin of 0.07.\nexport const CROWD = ${JSON.stringify({ L, big, small, n, rows: out })};\n`);
  process.exit(0);
}
